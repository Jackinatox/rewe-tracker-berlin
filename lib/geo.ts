export interface LatLng {
  lat: number;
  lng: number;
}

/** Great-circle distance in kilometres. */
export function haversineKm(a: LatLng, b: LatLng): number {
  const R = 6371;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

export function formatDistance(km: number): string {
  return km < 1 ? `${Math.round(km * 1000)} m` : `${km.toFixed(1).replace(".", ",")} km`;
}

/** GeoJSON MultiPolygon coordinates: polygon → ring → [lng, lat]. */
export type Districts = { name: string; polygons: number[][][][] }[];

function inRing(ring: number[][], lat: number, lng: number): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i] as [number, number];
    const [xj, yj] = ring[j] as [number, number];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Name of the district containing the point, or null if it's outside all of them. */
export function districtAt(districts: Districts, lat: number, lng: number): string | null {
  for (const d of districts) {
    for (const [outer, ...holes] of d.polygons) {
      if (outer && inRing(outer, lat, lng) && !holes.some((h) => inRing(h, lat, lng))) return d.name;
    }
  }
  return null;
}
